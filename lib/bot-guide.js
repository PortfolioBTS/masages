// вести к своей теме, а это проверяет тест: рассинхрон «кнопка есть, а
// ответа нет» не доживает до релиза.
//
// Честность текстов. Бот — это текст, который отдаёт сервер, а не часть
// шифрованного протокола: сервер мог бы сказать в нём что угодно. Поэтому в
// ответах нет ничего, что можно принять за проверку безопасности — ни
// отпечатков и хэшей ключей, ни ссылок. Про коды безопасности бот говорит
// только, ГДЕ они показаны в приложении, и просит сверять их вне этого чата.
// Сам чат с ботом не защищён сквозным шифрованием, поэтому каждый ответ,
// включая приветствие, об этом напоминает.
//
// Тексты описывают итоговое поведение мессенджера (временные аккаунты,
// обязательное E2EE в группах, поиск на устройстве, отметки о прочтении по
// умолчанию выключены), а не то, что есть на данный момент: гайд сверяется с
// кодом в конце работ. Имена кнопок и окон в кавычках «…» — как в интерфейсе.

// Предел текста сообщения (POST /api/messages): ответ бота — такое же
// сообщение, длиннее он быть не может.
const MAX_BOT_REPLY_LENGTH = 4000;

// Сколько символов запроса учитывается. Вопросу к боту хватает пары слов, а
// перебор длинной простыни по словам был бы лишней работой на каждое сообщение.
const MAX_INPUT_CHARS = 500;

// Отдельной последней строкой в каждом ответе: чат с ботом ходит открытым
// текстом, и пользователь не должен принять его за защищённый.
const BOT_DISCLAIMER = 'Чат со мной не защищён сквозным шифрованием — не пишите сюда личного';

// Ответ на непонятный текст. Дальше идёт тот же дисклеймер.
const UNKNOWN_HINT = 'Напишите „гайд“ или выберите тему кнопкой ниже';

// Последняя строка приветствия нового аккаунта.
const WELCOME_CLOSING = 'Напишите „гайд“, чтобы узнать, как всё устроено';

// Подписи кнопок над полем ввода в чате с ботом. Порядок — порядок кнопок.
// Клиент рисует не больше 6 кнопок с подписью не длиннее 60 символов, так что
// длину и число здесь тоже держим в этих пределах.
const QUICK_REPLIES = Object.freeze(['Гайд', 'Шифрование', 'Приглашения', 'Исчезающие', 'Аккаунт', 'Приватность']);

// ---------- Разбор запроса ----------

// «Гайд!», «ГАЙД», «гайд…» и «Всё, что умеешь?» должны давать то же, что
// «гайд» и «все что умеешь»: регистр, ё/е и пунктуация значения не имеют.
// Единственное исключение — «/»: он остаётся, чтобы «/start» отличался от
// просто слова «start».
function normalizeBotInput(text) {
    if (typeof text !== 'string') return '';
    return text
        .slice(0, MAX_INPUT_CHARS)
        // «ё» бывает одним символом и парой «е» + диакритика: NFC сводит оба вида к одному.
        .normalize('NFC')
        .toLowerCase()
        .replace(/ё/g, 'е')
        // Диакритики, оставшиеся после NFC (например, знак ударения), к слову не относятся.
        .replace(/\p{M}/gu, '')
        .replace(/[^\p{L}\p{N}\s/]+/gu, ' ')
        .replace(/\s+/g, ' ')
        .trim();
}

