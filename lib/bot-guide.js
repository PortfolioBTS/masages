// Полный текст ответа: заголовок, строки темы, пустая строка и дисклеймер
// отдельной последней строкой.
function composeReply(lines) {
    return [...lines, '', BOT_DISCLAIMER].join('\n');
}

const TOPICS = Object.freeze(TOPIC_DEFINITIONS.map(def => Object.freeze({
    id: def.id,
    label: def.label,
    phrases: Object.freeze([...def.phrases]),
    stems: Object.freeze([...def.stems]),
    text: composeReply([def.label, '', ...def.lines]),
})));

const TOPIC_BY_ID = new Map(TOPICS.map(topic => [topic.id, topic]));
const UNKNOWN_TEXT = composeReply([UNKNOWN_HINT]);

// ---------- Поиск темы ----------

// «/help» и «help» — одна и та же просьба, поэтому у слова с ведущим «/»
// пробуются оба вида. Основа «/start» от этого не страдает: слово «/start»
// начинается с неё само, а вот просто «start» — нет.
function wordForms(word) {
    return word.length > 1 && word.startsWith('/') ? [word, word.slice(1)] : [word];
}

function hasStem(words, stem) {
    return words.some(word => wordForms(word).some(form => form.startsWith(stem)));
}

function hasPhrase(words, phrase) {
    const parts = phrase.split(' ');
    for (let i = 0; i + parts.length <= words.length; i++) {
        if (parts.every((part, offset) => words[i + offset].startsWith(part))) return true;
    }
    return false;
}

// Идентификатор темы или null, если запрос ни на что не похож.
function detectTopic(text) {
    const normalized = normalizeBotInput(text);
    if (!normalized) return null;
    const words = normalized.split(' ');
    for (const topic of TOPICS) {
        if (topic.phrases.some(phrase => hasPhrase(words, phrase))) return topic.id;
    }
    for (const topic of TOPICS) {
        if (topic.stems.some(stem => hasStem(words, stem))) return topic.id;
    }
    return null;
}

// Ответ бота на сообщение пользователя: { topic: id | null, text }. Для
// неизвестного запроса topic = null, а text — подсказка, что написать.
function botReply(text) {
    const topic = TOPIC_BY_ID.get(detectTopic(text));
    return topic ? { topic: topic.id, text: topic.text } : { topic: null, text: UNKNOWN_TEXT };
}

