// Бот-помощник с гайдом по мессенджеру. Чистые функции «текст пользователя ->
// ответ»: без БД, сети и случайности. server.js только вызывает botReply() и
// кладёт результат в чат с ботом; всё остальное проверяется тестами без БД
// (test/bot-guide.test.js).
//
// Один источник для кнопок и ключевых слов. Подписи кнопок-подсказок
