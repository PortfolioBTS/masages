'use strict';
// Подгружается в процесс сервера сквозных тестов (node --require …):
// сервер — дочерний процесс тестового файла. Если тот завершится, не
// остановив сервер (тайм-аут раннера, Ctrl+C, падение), канал IPC
// закроется, и сервер выйдет сам, а не останется висеть с соединениями к
// тестовой базе. На поведение сервера не влияет: только слушает канал.

if (typeof process.send === 'function' && process.channel) {
    process.on('disconnect', () => process.exit(0));
    process.channel.unref(); // канал не должен сам держать процесс живым
}
